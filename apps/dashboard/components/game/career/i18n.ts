const _logKeysCovered: Record<LogKey, string> = pt;
void _logKeysCovered;

export type CareerKey = keyof typeof pt;
const DICTS: Record<string, Dict> = { pt, it, en };

export type CareerT = (key: CareerKey, vars?: Record<string, string | number>) => string;

export function useCareerT(): { t: CareerT; locale: string } {
  const { locale } = useI18n();
  const t = useCallback<CareerT>(
    (key, vars) => {
      const dict = DICTS[locale] ?? pt;
      let s = dict[key] ?? pt[key];
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
      return s;
    },
    [locale],
  );
  return { t, locale };
}

/** Importo in euro nella lingua giusta. */
export function money(n: number, locale: string): string {
  const tag = locale === "pt" ? "pt-PT" : locale === "it" ? "it-IT" : "en-GB";
  return new Intl.NumberFormat(tag, { style: "currency", currency: "EUR", maximumFractionDigits: 0 }).format(n);
}

/** Nome del mese di gioco: la stagione parte a settembre. */
export function monthName(month: number, locale: string): string {
  const tag = locale === "pt" ? "pt-PT" : locale === "it" ? "it-IT" : "en-GB";
  return new Intl.DateTimeFormat(tag, { month: "long" }).format(new Date(2024, (8 + month) % 12, 15));
}
